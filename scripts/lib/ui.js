export const checkList = (items, accent = '#2fc4b6', light = false) =>
  `<ul class="${light ? 'check-list-light space-y-3' : 'check-list'}" style="--accent: ${accent}">${items.map((i) => `<li>${i}</li>`).join('')}</ul>`;

export const dataTable = ({ head, rows, caption }) => `
          <div data-reveal class="data-table-wrap">
            <table class="data-table">
              ${caption ? `<caption class="sr-only">${caption}</caption>` : ''}
              <thead><tr>${head.map((h) => `<th scope="col">${h}</th>`).join('')}</tr></thead>
              <tbody>
                ${rows.map((r) => `<tr>${r.map((c, i) => (i === 0 ? `<th scope="row">${c}</th>` : `<td>${c}</td>`)).join('')}</tr>`).join('\n                ')}
              </tbody>
            </table>
          </div>`;

export const updatedLine = (date = SITE.updated) => {
  const d = new Date(`${date}T00:00:00Z`);
  const label = d.toLocaleDateString('en-US', { month: 'long', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
  return `<time datetime="${date}">${label}</time>`;
};
