export const crumbsNav = (crumbs) => `
        <nav aria-label="Breadcrumb" class="crumbs" data-reveal>
          <ol>
            ${crumbs
              .map((c, i) =>
                i === crumbs.length - 1
                  ? `<li aria-current="page">${esc(c.name)}</li>`
                  : `<li><a href="${c.url}">${esc(c.name)}</a></li>`
              )
              .join('\n            ')}
          </ol>
        </nav>`;

export const eyebrow = (text, dot = '#2fc4b6', light = false) =>
  light
    ? `<p data-reveal class="eyebrow-chip-light mb-5"><span class="size-1.5 rounded-full" style="background:${dot}"></span>${text}</p>`
    : `<p data-reveal class="eyebrow-chip mb-5"><span class="pulse-dot" style="--dot: ${dot}"></span>${text}</p>`;

export const ctaButtons = (primary = 'Book a Free Strategy Call', secondary = { label: 'See pricing & scope', href: '/contact.html' }) => `
            <div data-reveal class="mt-8 flex flex-wrap items-center gap-3">
              <a href="/book-meeting.html" class="cta cta-lg cta-coral">${primary}${arrow()}</a>
              ${secondary ? `<a href="${secondary.href}" class="cta cta-lg cta-ghost">${secondary.label}</a>` : ''}
            </div>`;

/**
 * Inner-page hero with breadcrumb and an answer-first card.
 * `answer` is the 40-60 word direct answer answer-engines quote; `facts` are
 * short label/value pairs shown under it.
 */
export const hero = ({ crumbs, eyebrowText, accent = '#2fc4b6', h1, lead, answer, answerLabel = 'Quick answer', facts = [], pills = [], primary, secondary }) => `
    <section class="page-hero">
      <span class="grid-field" aria-hidden="true"></span>
      <span class="orb -top-28 left-[8%] size-[420px] animate-drift" style="--orb: ${accent}; --orb-opacity: 0.28" aria-hidden="true"></span>
      <span class="orb top-1/3 -right-24 size-[380px] animate-drift-slow" style="--orb: #ff6b35; --orb-opacity: 0.18" aria-hidden="true"></span>

      <div class="main-container relative z-10">
        ${crumbsNav(crumbs)}
        <div class="mt-8 grid gap-10 lg:grid-cols-[1.12fr_0.88fr] lg:items-center lg:gap-14">
          <div>
            ${eyebrow(eyebrowText, accent)}
            <h1 data-reveal class="text-heading-4 sm:text-heading-3 lg:text-heading-2 font-semibold tracking-tight text-secondary">${h1}</h1>
            <p data-reveal class="text-tagline-1 mt-5 max-w-2xl text-secondary/65 md:text-lg">${lead}</p>
            ${ctaButtons(primary, secondary)}
            ${
              pills.length
                ? `<div data-reveal class="mt-8 flex flex-wrap gap-2">${pills.map((p) => `<span class="pill">${p}</span>`).join('')}</div>`
                : ''
            }
          </div>
          ${answer ? answerCard({ answer, facts, accent, label: answerLabel }) : ''}
        </div>
      </div>
    </section>`;

export const answerCard = ({ answer, facts = [], accent = '#2fc4b6', label = 'Quick answer' }) => `
          <aside data-reveal class="edge-card">
            <div class="answer-card p-6 md:p-8" style="--accent: ${accent}">
              <p class="text-tagline-3 flex items-center gap-2 font-semibold tracking-[0.14em] text-secondary/50 uppercase">
                <span class="icon-tile size-8 rounded-lg" style="--accent: ${accent}">${icon('sparkles', 'size-4')}</span>
                ${label}
              </p>
              <p class="text-tagline-1 mt-4 leading-relaxed text-secondary/85">${answer}</p>
              ${
                facts.length
                  ? `<dl class="mt-6 grid grid-cols-2 gap-3">${facts
                      .map(
                        (f) => `
                <div class="rounded-xl border border-secondary/[0.08] bg-secondary/[0.03] px-4 py-3">
                  <dt class="text-tagline-3 text-secondary/45">${f.label}</dt>
                  <dd class="text-tagline-2 mt-0.5 font-semibold text-secondary">${f.value}</dd>
                </div>`
                      )
                      .join('')}
              </dl>`
                  : ''
              }
            </div>
          </aside>`;

export const sectionHead = ({ eyebrowText, dot = '#2fc4b6', title, lead, center = false, light = false, id }) => `
        <div class="${center ? 'mx-auto text-center' : ''} mb-12 max-w-2xl md:mb-14"${id ? ` id="${id}"` : ''}>
          ${eyebrowText ? eyebrow(eyebrowText, dot, light) : ''}
          <h2 data-reveal class="text-heading-5 sm:text-heading-4 lg:text-heading-3 font-semibold tracking-tight ${light ? 'text-secondary' : 'text-secondary'}">${title}</h2>
          ${lead ? `<p data-reveal class="text-tagline-1 mt-4 ${light ? 'text-secondary/65' : 'text-secondary/60'}">${lead}</p>` : ''}
        </div>`;

