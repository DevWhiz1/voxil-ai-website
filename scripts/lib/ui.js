// Markup helpers for generated pages. Every helper returns an HTML string built
// from the dark-premium primitives in src/styles/ui.css, so generated pages
// look identical to the hand-written home page.
import { SITE } from '../../content/site.js';
import { arrow, icon, plus } from './icons.js';

export { arrow, icon };

export const esc = (s = '') =>
  String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

// Strips tags so HTML copy can be reused inside JSON-LD and meta tags.
export const plain = (s = '') =>
  String(s)
    .replace(/<[^>]+>/g, '')
    .replace(/&amp;/g, '&')
    .replace(/&nbsp;/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const jsonLd = (data) =>
  `<script type="application/ld+json">${JSON.stringify(data).replace(/</g, '\\u003c')}</script>`;

// ---------------------------------------------------------------------------
// Page shell
// ---------------------------------------------------------------------------
export const page = ({ path, title, description, body, schema = [] }) => `<!doctype html>
<html lang="en">
  <head>
    <Component src="src/components/shared/head-links.htm" />
    <title>${esc(title)}</title>
    <meta name="description" content="${esc(description)}" />
    <link rel="canonical" href="${SITE.url}${path}" />
    ${schema.map(jsonLd).join('\n    ')}
  </head>
  <body class="overflow-x-hidden bg-white">
    <!-- Generated by scripts/build-pages.js, edit the files in content/, not this file. -->
    <Component src="src/components/shared/header.htm" />
    <main>
${body}
      <Component src="src/components/shared/cta.htm" />
    </main>
    <Component src="src/components/shared/footer.htm" />
  </body>
</html>
`;

// ---------------------------------------------------------------------------
// Structured data
// ---------------------------------------------------------------------------
export const ORG_ID = `${SITE.url}/#organization`;

export const breadcrumbSchema = (crumbs) => ({
  '@context': 'https://schema.org',
  '@type': 'BreadcrumbList',
  itemListElement: crumbs.map((c, i) => ({
    '@type': 'ListItem',
    position: i + 1,
    name: c.name,
    item: `${SITE.url}${c.url}`,
  })),
});

export const faqSchema = (faqs) => ({
  '@context': 'https://schema.org',
  '@type': 'FAQPage',
  mainEntity: faqs.map((f) => ({
    '@type': 'Question',
    name: plain(f.q),
    acceptedAnswer: { '@type': 'Answer', text: plain(f.a) },
  })),
});

// WebPage node with speakable selectors, so voice assistants and answer
// engines can lift the quick-answer card verbatim.
export const webPageSchema = ({ path, title, description }) => ({
  '@context': 'https://schema.org',
  '@type': 'WebPage',
  '@id': `${SITE.url}${path}#webpage`,
  url: `${SITE.url}${path}`,
  name: title,
  description,
  inLanguage: 'en',
  isPartOf: { '@id': `${SITE.url}/#website` },
  publisher: { '@id': ORG_ID },
  dateModified: SITE.updated,
  speakable: { '@type': 'SpeakableSpecification', cssSelector: ['h1', '.answer-card'] },
});

